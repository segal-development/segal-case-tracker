"""PJUD public "Búsqueda por Fecha" (Invitado): pure parsers + browser driver.

Parsers are pure (no browser). The driver drives the real public UI in a FRESH,
non-logged-in browser context; it never replays a raw POST (the form carries a
reCAPTCHA v3 token generated by the page) and never touches a lawyer's session.
"""

from __future__ import annotations

import asyncio
import base64
import html as html_lib
import logging
import random
import re
from dataclasses import dataclass
from datetime import date, datetime
from typing import Any

logger = logging.getLogger(__name__)

PUBLICO_INDEX_URL = "https://oficinajudicialvirtual.pjud.cl/indexN.php"
PUBLICO_DOCU_URL = "https://oficinajudicialvirtual.pjud.cl/ADIR_871/civil/documentos/docu.php"
CONSULTA_FECHA_PATH = "ADIR_871/civil/consultaFechaCivil.php"
COMPETENCIA_CIVIL = "3"

#: Corte code → label stored with each causa.
CORTES = {"90": "C.A. de Santiago", "91": "C.A. de San Miguel"}

_TAG_RE = re.compile(r"<[^>]+>")


@dataclass(frozen=True)
class FilaResultado:
    rol: str
    fecha: date | None
    caratulado: str
    tribunal: str
    detalle: str  # short-lived (~30 min) JWT behind the lupa


@dataclass(frozen=True)
class Litigante:
    participante: str
    rut: str
    persona: str
    nombre: str


@dataclass(frozen=True)
class ModalCausa:
    rol: str
    fecha_ingreso: date | None
    caratulado: str
    tribunal: str


def _text(fragment: str) -> str:
    return re.sub(r"\s+", " ", html_lib.unescape(_TAG_RE.sub("", fragment))).strip()


def _parse_fecha(value: str) -> date | None:
    try:
        return datetime.strptime(value.strip(), "%d/%m/%Y").date()
    except ValueError:
        return None


_ROW_RE = re.compile(r"<tr\b[^>]*>(.*?)</tr>", re.DOTALL | re.IGNORECASE)
_CELL_RE = re.compile(r"<td\b[^>]*>(.*?)</td>", re.DOTALL | re.IGNORECASE)
_DETALLE_RE = re.compile(r"detalleCausaCivil\(\s*'([^']+)'")


def parse_resultados(html: str) -> list[FilaResultado]:
    """Rows of ``consultaFechaCivil.php``: lupa token, Rol, Fecha, Caratulado, Tribunal."""
    out: list[FilaResultado] = []
    for row in _ROW_RE.finditer(html or ""):
        body = row.group(1)
        cells = _CELL_RE.findall(body)
        token = _DETALLE_RE.search(body)
        if len(cells) < 5 or not token:
            continue
        out.append(
            FilaResultado(
                rol=_text(cells[1]),
                fecha=_parse_fecha(_text(cells[2])),
                caratulado=_text(cells[3]),
                tribunal=_text(cells[4]),
                detalle=token.group(1),
            )
        )
    return out


def solo_civiles(rows: list[FilaResultado]) -> list[FilaResultado]:
    """Only ROLs starting with "C-" (S3)."""
    return [r for r in rows if r.rol.upper().startswith("C-")]


def parse_litigantes(html: str) -> list[Litigante]:
    """Litigantes pane: columns Participante | Rut | Persona | Nombre o Razón Social."""
    pane = re.search(
        r'id="litigantesCiv"(.*?)(?=<div class="tab-pane|\Z)', html or "", re.DOTALL | re.IGNORECASE
    )
    if not pane:
        return []
    tbody = re.search(r"<tbody\b[^>]*>(.*?)</tbody>", pane.group(1), re.DOTALL | re.IGNORECASE)
    if not tbody:
        return []
    out: list[Litigante] = []
    for row in _ROW_RE.finditer(tbody.group(1)):
        cells = [_text(c) for c in _CELL_RE.findall(row.group(1))]
        if len(cells) < 4:
            continue
        out.append(Litigante(cells[0], cells[1], cells[2], cells[3]))
    return out


def sin_abogado_demandado(litigantes: list[Litigante]) -> bool:
    """L8: at least one ``DDO.`` and no code starting with ``AB.DDO`` / ``AP.DDO``."""
    codes = [(x.participante or "").strip().upper() for x in litigantes]
    if not any(c == "DDO." for c in codes):
        return False
    return not any(c.startswith(("AB.DDO", "AP.DDO")) for c in codes)


def parse_modal(html: str) -> ModalCausa:
    """ROL, F. Ing., carátula and tribunal from the modal header table."""
    rol = re.search(r"<strong>\s*ROL:\s*</strong>\s*([^<\s][^<]*)", html or "")
    fecha = re.search(r"<strong>\s*F\.\s*Ing\.:\s*</strong>\s*([^<]*)", html or "")
    trib = re.search(r"<strong>\s*Tribunal:\s*</strong>\s*([^<]*)", html or "")
    car = re.search(
        r"<strong>\s*F\.\s*Ing\.:\s*</strong>[^<]*</td>\s*<td[^>]*>(.*?)</td>", html or "", re.DOTALL
    )
    return ModalCausa(
        rol=_text(rol.group(1)) if rol else "",
        fecha_ingreso=_parse_fecha(fecha.group(1)) if fecha else None,
        caratulado=_text(car.group(1)) if car else "",
        tribunal=_text(trib.group(1)) if trib else "",
    )


def extraer_valor_demanda(html: str) -> str | None:
    m = re.search(r'name="valorEncTxtDmda"\s+value="([^"]+)"', html or "")
    return html_lib.unescape(m.group(1)) if m else None


# ---------------------------------------------------------------------------
# Browser driver
# ---------------------------------------------------------------------------

_FETCH_PDF_JS = """
async ({url, valor}) => {
  const body = new URLSearchParams({valorEncTxtDmda: valor});
  const resp = await fetch(url, {
    method: 'POST', credentials: 'include', body,
    headers: {'Content-Type': 'application/x-www-form-urlencoded'},
  });
  if (!resp.ok) return {status: resp.status, chunks: []};
  const buf = new Uint8Array(await resp.arrayBuffer());
  const chunks = [];
  const step = 0x8000;
  for (let i = 0; i < buf.length; i += step) {
    let s = '';
    const part = buf.subarray(i, i + step);
    for (let j = 0; j < part.length; j++) s += String.fromCharCode(part[j]);
    chunks.push(btoa(s));
  }
  return {status: resp.status, ctype: resp.headers.get('content-type') || '', chunks};
}
"""

_SET_DATES_JS = """
([desde, hasta]) => { $('#fecDesde').val(desde); $('#fecHasta').val(hasta); }
"""


class PublicoFechaDriver:
    """Drives the public Búsqueda por Fecha in a page of a fresh, logged-out context."""

    def __init__(self, page: Any, *, pause: tuple[float, float] = (1.0, 3.0)):
        self._page = page
        self._pause_range = pause
        self._ready = False

    async def _pause(self) -> None:
        lo, hi = self._pause_range
        if hi > 0:
            await asyncio.sleep(random.uniform(lo, hi))

    @staticmethod
    async def _limiter(kind: str) -> None:
        from app.scrapper.pjud.resilience.rate_limiter import pjud_action_limiter

        await pjud_action_limiter(kind).acquire()

    async def _open_form(self) -> None:
        if self._ready:
            return
        await self._limiter("list")
        page = self._page
        await page.goto(PUBLICO_INDEX_URL, wait_until="domcontentloaded")
        await self._pause()
        await page.evaluate("accesoConsultaCausas()")
        await page.wait_for_selector("#formConsultaFec", state="attached", timeout=30000)
        await page.click("a[href='#BusFecha']")
        await page.select_option("#fecCompetencia", COMPETENCIA_CIVIL)
        self._ready = True

    async def listar_tribunales(self, corte: str) -> list[tuple[str, str]]:
        """``(value, name)`` of #fecTribunal for a corte, skipping placeholders."""
        await self._open_form()
        await self._pause()
        page = self._page
        # Choosing Civil already fills #fecTribunal with every civil court of the country
        # (230 seen live 27/11); empty it so the wait below sees the corte's own reload.
        await page.evaluate("() => { const s = document.querySelector('#fecTribunal'); if (s) s.innerHTML = ''; }")
        await page.select_option("#corteFec", str(corte))
        await page.wait_for_function(
            "document.querySelectorAll('#fecTribunal option').length > 2", timeout=30000
        )
        opts = await page.eval_on_selector_all(
            "#fecTribunal option",
            "els => els.map(e => [e.value, (e.textContent || '').trim()])",
        )
        return [(v, n) for v, n in opts if v not in ("", "0")]

    async def buscar(self, corte: str, tribunal: str, desde: date, hasta: date) -> list[FilaResultado]:
        await self._open_form()
        await self._limiter("list")
        await self._pause()
        page = self._page
        await page.select_option("#corteFec", str(corte))
        await page.wait_for_function(
            "document.querySelectorAll('#fecTribunal option').length > 2", timeout=30000
        )
        await page.select_option("#fecTribunal", str(tribunal))
        await page.evaluate(_SET_DATES_JS, [desde.strftime("%d/%m/%Y"), hasta.strftime("%d/%m/%Y")])
        async with page.expect_response(lambda r: CONSULTA_FECHA_PATH in r.url, timeout=60000) as info:
            await page.click("#btnConConsultaFec")
        resp = await info.value
        return parse_resultados(await resp.text())

    async def abrir_detalle(self, fila: FilaResultado) -> str:
        """Click the row's lupa; return the modal HTML once "Litigantes" is loaded."""
        await self._limiter("detail")
        await self._pause()
        page = self._page
        # The previous modal stays shown ("modal in") and would intercept a lupa click, so
        # hide and empty it, then call the page's own detalleCausaCivil(token): it runs the
        # reCAPTCHA v3 step itself and replaces the modal HTML (seen live 27/11).
        await page.evaluate(
            "() => { const m = $('#modalDetalleCivil'); if (m.length) { m.modal('hide'); m.empty(); }"
            " $('.modal-backdrop').remove(); $('body').removeClass('modal-open'); }"
        )
        await page.evaluate("(t) => detalleCausaCivil(t)", fila.detalle)
        await page.wait_for_function(
            "(document.querySelector('#modalDetalleCivil')||{}).innerText?.includes('Litigantes')",
            timeout=60000,
        )
        return await page.inner_html("#modalDetalleCivil")

    async def descargar_demanda(self, valor: str) -> bytes | None:
        """POST docu.php in-page; bytes are read in chunks. ``None`` when not a PDF."""
        await self._limiter("document")
        await self._pause()
        res = await self._page.evaluate(_FETCH_PDF_JS, {"url": PUBLICO_DOCU_URL, "valor": valor})
        if not res or res.get("status") != 200 or "pdf" not in (res.get("ctype") or "").lower():
            return None
        return b"".join(base64.b64decode(c) for c in res.get("chunks", []))
